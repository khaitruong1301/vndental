-- 4. BỆNH NHÂN (BN-01 … BN-06)
-- =============================================================================
CREATE TABLE patients (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_code      varchar(20)  NOT NULL UNIQUE
                    DEFAULT 'BN' || to_char(nextval('patient_code_seq'), 'FM000000'),
  full_name         varchar(150) NOT NULL,
  date_of_birth     date,
  gender            varchar(10)  CHECK (gender IN ('MALE', 'FEMALE', 'OTHER')),
  phone             varchar(20),
  email             varchar(150),
  address           text,
  medical_history   text,
  note              text,
  is_legacy         boolean      NOT NULL DEFAULT false,
  legacy_record_no  varchar(50),
  last_visit_at     timestamptz,
  status            varchar(10)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'ARCHIVED')),
  archived_at       timestamptz,
  created_by        bigint REFERENCES staff(id),
  updated_by        bigint REFERENCES staff(id),
  created_at        timestamptz  NOT NULL DEFAULT now(),
  updated_at        timestamptz  NOT NULL DEFAULT now(),
  CHECK (status <> 'ARCHIVED' OR archived_at IS NOT NULL)
);
CREATE INDEX ix_patients_phone ON patients (phone);
CREATE INDEX ix_patients_phone_dob ON patients (phone, date_of_birth);
CREATE INDEX ix_patients_name_trgm ON patients USING gin (lower(full_name) gin_trgm_ops);
CREATE INDEX ix_patients_last_visit ON patients (last_visit_at);
COMMENT ON TABLE patients IS 'Hồ sơ bệnh nhân. SĐT KHÔNG phải khóa định danh — một SĐT có thể thuộc nhiều bệnh nhân (mục 6.2). is_legacy = hồ sơ số hóa từ giấy (BN-06).';

CREATE TABLE patient_guardians (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id   bigint       NOT NULL REFERENCES patients(id),
  full_name    varchar(150) NOT NULL,
  relationship varchar(50)  NOT NULL,
  phone        varchar(20)  NOT NULL,
  is_primary   boolean      NOT NULL DEFAULT true,
  note         text,
  created_at   timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_patient_guardians_patient ON patient_guardians (patient_id);
CREATE INDEX ix_patient_guardians_phone ON patient_guardians (phone);
COMMENT ON TABLE patient_guardians IS 'Người giám hộ cho bệnh nhân dưới 15 tuổi (BN-03).';

CREATE TABLE patient_documents (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id    bigint       NOT NULL REFERENCES patients(id),
  document_type varchar(20)  NOT NULL DEFAULT 'LEGACY_SCAN'
                CHECK (document_type IN ('LEGACY_SCAN', 'XRAY', 'PHOTO', 'OTHER')),
  file_path     text         NOT NULL,
  file_name     varchar(255) NOT NULL,
  mime_type     varchar(100),
  file_size     bigint,
  description   text,
  uploaded_by   bigint REFERENCES staff(id),
  uploaded_at   timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_patient_documents_patient ON patient_documents (patient_id);
COMMENT ON TABLE patient_documents IS 'File đính kèm hồ sơ: ảnh scan hồ sơ giấy cũ (BN-06), X-quang, ảnh chụp.';

-- =============================================================================
-- 5. LỊCH HẸN (LH-01 … LH-09)
-- =============================================================================
CREATE TABLE appointments (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_group_id uuid        NOT NULL DEFAULT gen_random_uuid(),
  patient_id       bigint      NOT NULL REFERENCES patients(id),
  doctor_id        bigint      NOT NULL REFERENCES staff(id),
  chair_id         smallint    NOT NULL REFERENCES chairs(id),
  service_id       bigint REFERENCES services(id),
  start_at         timestamptz NOT NULL,
  end_at           timestamptz NOT NULL,
  status           varchar(15) NOT NULL DEFAULT 'BOOKED'
                   CHECK (status IN ('BOOKED', 'ARRIVED', 'IN_TREATMENT', 'COMPLETED', 'CANCELLED')),
  source           varchar(20) NOT NULL DEFAULT 'RECEPTION'
                   CHECK (source IN ('RECEPTION', 'DOCTOR_FOLLOW_UP', 'WALK_IN')),
  note             text,
  checked_in_at    timestamptz,
  cancel_reason_id smallint REFERENCES cancel_reasons(id),
  cancel_note      text,
  cancelled_by     bigint REFERENCES staff(id),
  cancelled_at     timestamptz,
  created_by       bigint REFERENCES staff(id),
  updated_by       bigint REFERENCES staff(id),
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),

  -- Một lịch = 1 khung 30 phút, bắt đầu ở phút :00 hoặc :30
  CONSTRAINT chk_appointments_slot CHECK (
    end_at = start_at + interval '30 minutes'
    AND date_trunc('minute', clinic_local(start_at)) = clinic_local(start_at)
    AND extract(minute FROM clinic_local(start_at))::int % 30 = 0),
  CONSTRAINT chk_appointments_cancel CHECK (
    status <> 'CANCELLED' OR (cancel_reason_id IS NOT NULL AND cancelled_at IS NOT NULL)),
  CONSTRAINT chk_appointments_checkin CHECK (
    status NOT IN ('ARRIVED', 'IN_TREATMENT', 'COMPLETED') OR checked_in_at IS NOT NULL),

  -- LH-07: không trùng giờ trên cùng ghế / cùng bác sĩ (bỏ qua lịch đã hủy)
  CONSTRAINT ex_appointments_chair_overlap EXCLUDE USING gist
    (chair_id WITH =, tstzrange(start_at, end_at) WITH &&) WHERE (status <> 'CANCELLED'),
  CONSTRAINT ex_appointments_doctor_overlap EXCLUDE USING gist
    (doctor_id WITH =, tstzrange(start_at, end_at) WITH &&) WHERE (status <> 'CANCELLED')
);
CREATE INDEX ix_appointments_patient ON appointments (patient_id, start_at DESC);
CREATE INDEX ix_appointments_start ON appointments (start_at);
CREATE INDEX ix_appointments_group ON appointments (booking_group_id);
COMMENT ON TABLE appointments IS 'Lịch hẹn: mỗi bản ghi = 1 bệnh nhân + 1 bác sĩ + 1 ghế + 1 khung 30 phút. Việc dài đặt nhiều khung liên tiếp cùng booking_group_id. "Không đến" = hủy với lý do is_no_show.';

CREATE TABLE appointment_reminders (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id      bigint      NOT NULL REFERENCES appointments(id),
  channel             varchar(10) NOT NULL CHECK (channel IN ('CALL', 'SMS', 'ZALO')),
  result              varchar(25) NOT NULL CHECK (result IN (
                        'CONFIRMED', 'NO_ANSWER', 'WRONG_NUMBER', 'RESCHEDULE_REQUESTED',
                        'CANCEL_REQUESTED', 'SENT', 'DELIVERED', 'FAILED')),
  recipient_phone     varchar(20),
  message_content     text,
  provider_message_id varchar(100),
  note                text,
  performed_by        bigint REFERENCES staff(id),
  performed_at        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_appointment_reminders_appt ON appointment_reminders (appointment_id);
COMMENT ON TABLE appointment_reminders IS 'Kết quả gọi nhắc lịch (LH-05) và tin nhắn SMS/Zalo đã gửi (LH-06).';

-- =============================================================================
-- 6. LIỆU TRÌNH (DT-04, DT-05)
-- =============================================================================
CREATE TABLE treatment_plans (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_code         varchar(20)   NOT NULL UNIQUE
                    DEFAULT 'LT' || to_char(nextval('treatment_plan_code_seq'), 'FM000000'),
  patient_id        bigint        NOT NULL REFERENCES patients(id),
  primary_doctor_id bigint        NOT NULL REFERENCES staff(id),
  service_id        bigint REFERENCES services(id),
  name              varchar(200)  NOT NULL,
  plan_type         varchar(15)   NOT NULL CHECK (plan_type IN ('ORTHODONTIC', 'IMPLANT', 'OTHER')),
  total_price       numeric(14,2) NOT NULL CHECK (total_price >= 0),
  expected_sessions smallint      NOT NULL CHECK (expected_sessions > 0),
  status            varchar(10)   NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'COMPLETED', 'CANCELLED')),
  started_on        date          NOT NULL DEFAULT current_date,
  ended_on          date,
  note              text,
  created_by        bigint REFERENCES staff(id),
  updated_by        bigint REFERENCES staff(id),
  created_at        timestamptz   NOT NULL DEFAULT now(),
  updated_at        timestamptz   NOT NULL DEFAULT now(),
  CHECK (status = 'ACTIVE' OR ended_on IS NOT NULL)
);
CREATE INDEX ix_treatment_plans_patient ON treatment_plans (patient_id);
COMMENT ON TABLE treatment_plans IS 'Liệu trình trọn gói (niềng, implant): tổng giá, số buổi dự kiến (DT-05).';

CREATE TABLE treatment_plan_installments (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  treatment_plan_id bigint        NOT NULL REFERENCES treatment_plans(id) ON DELETE CASCADE,
  installment_no    smallint      NOT NULL CHECK (installment_no > 0),
  due_date          date,
  amount            numeric(14,2) NOT NULL CHECK (amount > 0),
  note              text,
  UNIQUE (treatment_plan_id, installment_no)
);
COMMENT ON TABLE treatment_plan_installments IS 'Kế hoạch các đợt thanh toán của liệu trình (giả định 5).';

-- =============================================================================
-- 7. PHIẾU ĐIỀU TRỊ, ĐƠN THUỐC, VẬT TƯ (DT-01 … DT-09)
-- =============================================================================
CREATE TABLE treatment_records (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  record_code       varchar(20) NOT NULL UNIQUE
                    DEFAULT 'PDT' || to_char(nextval('treatment_record_code_seq'), 'FM000000'),
  patient_id        bigint      NOT NULL REFERENCES patients(id),
  appointment_id    bigint UNIQUE REFERENCES appointments(id),
  primary_doctor_id bigint      NOT NULL REFERENCES staff(id),
  chair_id          smallint REFERENCES chairs(id),
  visit_at          timestamptz NOT NULL DEFAULT now(),
  treatment_plan_id bigint REFERENCES treatment_plans(id),
  plan_session_no   smallint CHECK (plan_session_no > 0),
  chief_complaint   text,
  diagnosis         text,
  note              text,
  status            varchar(20) NOT NULL DEFAULT 'DRAFT'
                    CHECK (status IN ('DRAFT', 'PENDING_PAYMENT', 'INVOICED', 'CANCELLED')),
  created_by        bigint REFERENCES staff(id),
  updated_by        bigint REFERENCES staff(id),
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  CHECK (plan_session_no IS NULL OR treatment_plan_id IS NOT NULL)
);
CREATE INDEX ix_treatment_records_patient ON treatment_records (patient_id, visit_at DESC);
CREATE INDEX ix_treatment_records_status ON treatment_records (status);
CREATE UNIQUE INDEX ux_treatment_records_plan_session
  ON treatment_records (treatment_plan_id, plan_session_no)
  WHERE plan_session_no IS NOT NULL AND status <> 'CANCELLED';
COMMENT ON TABLE treatment_records IS 'Phiếu điều trị: 1 bác sĩ chính; DRAFT → PENDING_PAYMENT (Chờ thanh toán) → INVOICED (DT-02). Gắn buổi liệu trình qua treatment_plan_id + plan_session_no (DT-04).';

CREATE TABLE treatment_record_items (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  treatment_record_id  bigint        NOT NULL REFERENCES treatment_records(id) ON DELETE CASCADE,
  line_no              smallint      NOT NULL,
  service_id           bigint        NOT NULL REFERENCES services(id),
  tooth_code           varchar(5)    NOT NULL,
  performing_doctor_id bigint        NOT NULL REFERENCES staff(id),
  quantity             numeric(8,2)  NOT NULL DEFAULT 1 CHECK (quantity > 0),
  is_plan_package      boolean       NOT NULL DEFAULT false,
  note                 text,
  created_at           timestamptz   NOT NULL DEFAULT now(),
  updated_at           timestamptz   NOT NULL DEFAULT now(),
  UNIQUE (treatment_record_id, line_no),
  -- FDI: răng vĩnh viễn 11–48, răng sữa 51–85; hoặc theo hàm
  CONSTRAINT chk_tooth_code CHECK (
    tooth_code ~ '^([1-4][1-8]|[5-8][1-5])$' OR tooth_code IN ('FULL', 'UPPER', 'LOWER'))
);
CREATE INDEX ix_treatment_record_items_doctor ON treatment_record_items (performing_doctor_id);
COMMENT ON TABLE treatment_record_items IS 'Dòng việc trên phiếu: dịch vụ + số răng FDI (hoặc FULL/UPPER/LOWER) + bác sĩ thực hiện (mục 6.1). is_plan_package = dòng thuộc liệu trình trọn gói → giá 0 trên hóa đơn buổi.';

CREATE TABLE prescription_items (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  treatment_record_id bigint        NOT NULL REFERENCES treatment_records(id) ON DELETE CASCADE,
  item_id             bigint REFERENCES items(id),
  medicine_name       varchar(200)  NOT NULL,
  dosage              text          NOT NULL,
  quantity            numeric(10,2) NOT NULL CHECK (quantity > 0),
  unit                varchar(30),
  is_external         boolean       NOT NULL DEFAULT false,
  note                text,
  created_at          timestamptz   NOT NULL DEFAULT now(),
  updated_at          timestamptz   NOT NULL DEFAULT now(),
  CHECK (is_external OR item_id IS NOT NULL)
);
CREATE INDEX ix_prescription_items_record ON prescription_items (treatment_record_id);
COMMENT ON TABLE prescription_items IS 'Đơn thuốc theo lần khám (DT-03). is_external = mua ngoài: không trừ kho, không tính tiền.';

CREATE TABLE treatment_record_materials (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
