CREATE TABLE chairs (
  id         smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code       varchar(20)  NOT NULL UNIQUE,
  name       varchar(100) NOT NULL,
  is_active  boolean      NOT NULL DEFAULT true,
  note       text,
  created_at timestamptz  NOT NULL DEFAULT now()
);
COMMENT ON TABLE chairs IS 'Ghế nha khoa (3 ghế).';

CREATE TABLE services (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code             varchar(30)  NOT NULL UNIQUE,
  name             varchar(200) NOT NULL,
  category         varchar(100),
  unit             varchar(30)  NOT NULL DEFAULT 'lần',
  tooth_scope      varchar(10)  NOT NULL DEFAULT 'TOOTH'
                   CHECK (tooth_scope IN ('TOOTH', 'JAW', 'ANY')),
  default_slots    smallint     NOT NULL DEFAULT 1 CHECK (default_slots > 0),
  is_active        boolean      NOT NULL DEFAULT true,
  description      text,
  created_at       timestamptz  NOT NULL DEFAULT now(),
  updated_at       timestamptz  NOT NULL DEFAULT now()
);
COMMENT ON TABLE services IS 'Danh mục dịch vụ. tooth_scope: TOOTH = theo răng, JAW = theo hàm/toàn hàm, ANY = cả hai. default_slots = số khung 30 phút gợi ý khi đặt lịch.';

CREATE TABLE service_prices (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_id     bigint        NOT NULL REFERENCES services(id),
  price          numeric(14,2) NOT NULL CHECK (price >= 0),
  effective_from date          NOT NULL,
  note           text,
  created_by     bigint REFERENCES staff(id),
  created_at     timestamptz   NOT NULL DEFAULT now(),
  UNIQUE (service_id, effective_from)
);
COMMENT ON TABLE service_prices IS 'Bảng giá dịch vụ theo ngày hiệu lực; tạo giá mới, không ghi đè giá cũ (QT-02).';

CREATE TABLE items (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code           varchar(30)   NOT NULL UNIQUE,
  name           varchar(200)  NOT NULL,
  item_type      varchar(10)   NOT NULL CHECK (item_type IN ('SUPPLY', 'MEDICINE')),
  unit           varchar(30)   NOT NULL,
  current_stock  numeric(12,2) NOT NULL DEFAULT 0,
  min_stock      numeric(12,2) NOT NULL DEFAULT 0 CHECK (min_stock >= 0),
  default_dosage text,
  is_active      boolean       NOT NULL DEFAULT true,
  note           text,
  created_at     timestamptz   NOT NULL DEFAULT now(),
  updated_at     timestamptz   NOT NULL DEFAULT now()
);
COMMENT ON TABLE items IS 'Vật tư (SUPPLY) và thuốc (MEDICINE) quản lý tồn kho chung (QT-03, QT-04). current_stock do trigger từ stock_movements cập nhật.';

CREATE TABLE item_prices (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id        bigint        NOT NULL REFERENCES items(id),
  price          numeric(14,2) NOT NULL CHECK (price >= 0),
  effective_from date          NOT NULL,
  note           text,
  created_by     bigint REFERENCES staff(id),
  created_at     timestamptz   NOT NULL DEFAULT now(),
  UNIQUE (item_id, effective_from)
);
COMMENT ON TABLE item_prices IS 'Giá bán thuốc theo ngày hiệu lực (QT-02).';

CREATE TABLE service_material_norms (
  service_id bigint        NOT NULL REFERENCES services(id) ON DELETE CASCADE,
  item_id    bigint        NOT NULL REFERENCES items(id),
  quantity   numeric(10,2) NOT NULL CHECK (quantity > 0),
  PRIMARY KEY (service_id, item_id)
);
COMMENT ON TABLE service_material_norms IS 'Định mức vật tư cho 1 đơn vị dịch vụ (QT-03, DT-06).';

CREATE TABLE cancel_reasons (
  id         smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code       varchar(30)  NOT NULL UNIQUE,
  name       varchar(150) NOT NULL,
  is_no_show boolean      NOT NULL DEFAULT false,
  is_active  boolean      NOT NULL DEFAULT true,
  sort_order smallint     NOT NULL DEFAULT 0
);
COMMENT ON TABLE cancel_reasons IS 'Danh mục lý do hủy lịch; is_no_show = "Không đến" (LH-04, BC-04).';

