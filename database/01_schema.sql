CREATE FUNCTION trg_record_materials_stock() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'UPDATE' AND NEW.item_id = OLD.item_id AND NEW.actual_quantity = OLD.actual_quantity THEN
    RETURN NULL;
  END IF;
  IF TG_OP IN ('UPDATE', 'DELETE') THEN
    PERFORM add_stock_movement(OLD.item_id, 'TREATMENT_USE', OLD.actual_quantity,
                               OLD.treatment_record_id, 'Hoàn kho do sửa phiếu điều trị');
  END IF;
  IF TG_OP IN ('INSERT', 'UPDATE') THEN
    PERFORM add_stock_movement(NEW.item_id, 'TREATMENT_USE', -NEW.actual_quantity,
                               NEW.treatment_record_id, 'Trừ vật tư theo phiếu điều trị');
  END IF;
  RETURN NULL;
END $$;

CREATE FUNCTION trg_prescription_items_stock() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'UPDATE' AND NEW.item_id IS NOT DISTINCT FROM OLD.item_id
     AND NEW.quantity = OLD.quantity AND NEW.is_external = OLD.is_external THEN
    RETURN NULL;
  END IF;
  IF TG_OP IN ('UPDATE', 'DELETE') AND NOT OLD.is_external AND OLD.item_id IS NOT NULL THEN
    PERFORM add_stock_movement(OLD.item_id, 'DISPENSE', OLD.quantity,
                               OLD.treatment_record_id, 'Hoàn kho do sửa đơn thuốc');
  END IF;
  IF TG_OP IN ('INSERT', 'UPDATE') AND NOT NEW.is_external AND NEW.item_id IS NOT NULL THEN
    PERFORM add_stock_movement(NEW.item_id, 'DISPENSE', -NEW.quantity,
                               NEW.treatment_record_id, 'Xuất thuốc theo đơn');
  END IF;
  RETURN NULL;
END $$;

-- Điền vật tư theo định mức cho phiếu (giữ nguyên số lượng thực dùng bác sĩ đã chỉnh)
CREATE FUNCTION fill_material_norms(p_record_id bigint) RETURNS integer
LANGUAGE plpgsql AS $$
DECLARE v_count integer;
BEGIN
  INSERT INTO treatment_record_materials (treatment_record_id, item_id, norm_quantity, actual_quantity)
  SELECT p_record_id, n.item_id, sum(n.quantity * tri.quantity), sum(n.quantity * tri.quantity)
  FROM treatment_record_items tri
  JOIN service_material_norms n ON n.service_id = tri.service_id
  WHERE tri.treatment_record_id = p_record_id
  GROUP BY n.item_id
  ON CONFLICT (treatment_record_id, item_id) DO UPDATE SET norm_quantity = EXCLUDED.norm_quantity;
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END $$;

-- Cập nhật tồn kho + DT-07 cảnh báo khi vừa xuống dưới ngưỡng
CREATE FUNCTION trg_stock_movements_apply() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  v_new  numeric;
  v_min  numeric;
  v_name text;
  v_unit text;
BEGIN
  UPDATE items SET current_stock = current_stock + NEW.quantity
  WHERE id = NEW.item_id
  RETURNING current_stock, min_stock, name, unit INTO v_new, v_min, v_name, v_unit;

  IF v_new < v_min AND v_new - NEW.quantity >= v_min THEN
    INSERT INTO notifications (recipient_role_id, notification_type, title, content, ref_table, ref_id)
    SELECT r.id, 'LOW_STOCK', 'Dưới ngưỡng tồn kho: ' || v_name,
           format('Tồn kho còn %s %s, ngưỡng tối thiểu %s %s', fmt_qty(v_new), v_unit, fmt_qty(v_min), v_unit),
           'items', NEW.item_id
    FROM roles r WHERE r.code = 'MANAGER';
  END IF;
  RETURN NULL;
END $$;

-- Tính lại tổng tiền, đã thu, trạng thái hóa đơn
CREATE FUNCTION refresh_invoice_totals(p_invoice_id bigint) RETURNS void
LANGUAGE sql AS $$
  WITH l AS (
    SELECT coalesce(sum(quantity * unit_price), 0) AS gross,
           coalesce(sum(discount_amount), 0)       AS discount,
           coalesce(sum(line_total), 0)            AS total
    FROM invoice_items WHERE invoice_id = p_invoice_id
  ), p AS (
    SELECT coalesce(sum(amount), 0) AS paid FROM payments WHERE invoice_id = p_invoice_id
  )
  UPDATE invoices i
  SET subtotal        = l.gross,
      discount_amount = l.discount,
      total_amount    = l.total,
      paid_amount     = p.paid,
      status = CASE
                 WHEN i.status = 'VOIDED'           THEN 'VOIDED'
                 WHEN p.paid = 0 AND l.total > 0    THEN 'UNPAID'
                 WHEN p.paid < l.total              THEN 'PARTIALLY_PAID'
                 ELSE 'PAID'
               END
  FROM l, p
  WHERE i.id = p_invoice_id;
$$;

CREATE FUNCTION trg_invoice_items_refresh() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP IN ('UPDATE', 'DELETE') THEN
    PERFORM refresh_invoice_totals(OLD.invoice_id);
  END IF;
  IF TG_OP = 'INSERT' OR (TG_OP = 'UPDATE' AND NEW.invoice_id <> OLD.invoice_id) THEN
    PERFORM refresh_invoice_totals(NEW.invoice_id);
  END IF;
  RETURN NULL;
END $$;

-- TT-01 + TT-02: lập hóa đơn từ phiếu điều trị "Chờ thanh toán", chụp giá hiện hành
CREATE FUNCTION create_invoice_from_treatment_record(p_record_id bigint, p_issued_by bigint,
                                                     p_issued_at timestamptz DEFAULT now())
RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE
  v_rec        treatment_records%ROWTYPE;
  v_invoice_id bigint;
  v_today      date := clinic_local(p_issued_at)::date;
  v_lines      integer;
BEGIN
  SELECT * INTO v_rec FROM treatment_records WHERE id = p_record_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Không tìm thấy phiếu điều trị %', p_record_id USING ERRCODE = 'no_data_found';
  END IF;
  IF v_rec.status <> 'PENDING_PAYMENT' THEN
    RAISE EXCEPTION 'Phiếu % không ở trạng thái Chờ thanh toán', v_rec.record_code USING ERRCODE = 'check_violation';
  END IF;

  INSERT INTO invoices (patient_id, invoice_type, treatment_record_id, issued_by, issued_at)
  VALUES (v_rec.patient_id, 'VISIT', v_rec.id, p_issued_by, p_issued_at)
  RETURNING id INTO v_invoice_id;

  INSERT INTO invoice_items (invoice_id, line_no, line_type, treatment_record_item_id, service_id,
                             description, tooth_code, performing_doctor_id, quantity, unit_price)
  SELECT v_invoice_id, row_number() OVER (ORDER BY tri.line_no), 'SERVICE', tri.id, tri.service_id,
         s.name, tri.tooth_code, tri.performing_doctor_id, tri.quantity,
         CASE WHEN tri.is_plan_package THEN 0 ELSE get_service_price(tri.service_id, v_today) END
  FROM treatment_record_items tri
  JOIN services s ON s.id = tri.service_id
  WHERE tri.treatment_record_id = p_record_id;
  GET DIAGNOSTICS v_lines = ROW_COUNT;

  INSERT INTO invoice_items (invoice_id, line_no, line_type, prescription_item_id, item_id,
                             description, quantity, unit_price)
  SELECT v_invoice_id, v_lines + row_number() OVER (ORDER BY pi.id), 'MEDICINE', pi.id, pi.item_id,
         pi.medicine_name, pi.quantity, get_item_price(pi.item_id, v_today)
  FROM prescription_items pi
  WHERE pi.treatment_record_id = p_record_id AND NOT pi.is_external;

  UPDATE treatment_records SET status = 'INVOICED' WHERE id = p_record_id;
  RETURN v_invoice_id;
END $$;

-- Hóa đơn liệu trình trọn gói (thu theo đợt bằng TT-04)
CREATE FUNCTION create_invoice_for_treatment_plan(p_plan_id bigint, p_issued_by bigint,
                                                  p_issued_at timestamptz DEFAULT now())
RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE
  v_plan       treatment_plans%ROWTYPE;
  v_invoice_id bigint;
BEGIN
  SELECT * INTO v_plan FROM treatment_plans WHERE id = p_plan_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Không tìm thấy liệu trình %', p_plan_id USING ERRCODE = 'no_data_found';
  END IF;
  IF v_plan.status = 'CANCELLED' THEN
    RAISE EXCEPTION 'Liệu trình % đã hủy', v_plan.plan_code USING ERRCODE = 'check_violation';
  END IF;

  INSERT INTO invoices (patient_id, invoice_type, treatment_plan_id, issued_by, issued_at)
  VALUES (v_plan.patient_id, 'TREATMENT_PLAN', v_plan.id, p_issued_by, p_issued_at)
  RETURNING id INTO v_invoice_id;

  INSERT INTO invoice_items (invoice_id, line_no, line_type, service_id, description,
                             performing_doctor_id, quantity, unit_price)
  VALUES (v_invoice_id, 1, 'TREATMENT_PLAN', v_plan.service_id, 'Liệu trình: ' || v_plan.name,
          v_plan.primary_doctor_id, 1, v_plan.total_price);
  RETURN v_invoice_id;
END $$;

-- TT-03 / mục 6.3: nhập giảm theo tổng, phân bổ xuống dòng theo tỷ lệ giá trị
CREATE FUNCTION apply_invoice_discount(p_invoice_id bigint, p_discount numeric,
                                       p_reason text, p_staff_id bigint)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
  v_status       varchar;
  v_paid         numeric;
  v_old_total    numeric;
  v_old_discount numeric;
  v_gross        numeric;
BEGIN
  SELECT status, paid_amount, total_amount, discount_amount
  INTO v_status, v_paid, v_old_total, v_old_discount
  FROM invoices WHERE id = p_invoice_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Không tìm thấy hóa đơn %', p_invoice_id USING ERRCODE = 'no_data_found';
  END IF;
  IF v_status = 'VOIDED' THEN
    RAISE EXCEPTION 'Hóa đơn đã hủy' USING ERRCODE = 'check_violation';
  END IF;
  IF p_discount > 0 AND coalesce(btrim(p_reason), '') = '' THEN
    RAISE EXCEPTION 'Phải ghi lý do giảm giá' USING ERRCODE = 'check_violation';
  END IF;
  -- Hóa đơn đã thu tiền: đổi giảm giá là điều chỉnh hóa đơn (TT-08) — chỉ Quản lý, có lý do, có lịch sử
  IF v_paid > 0 THEN
    IF NOT EXISTS (SELECT 1 FROM staff s JOIN roles r ON r.id = s.role_id
                   WHERE s.id = p_staff_id AND r.code = 'MANAGER' AND s.is_active) THEN
      RAISE EXCEPTION 'Hóa đơn đã thu tiền — chỉ Quản lý được điều chỉnh giảm giá (TT-08)'
        USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF coalesce(btrim(p_reason), '') = '' THEN
      RAISE EXCEPTION 'Phải ghi lý do điều chỉnh hóa đơn' USING ERRCODE = 'check_violation';
    END IF;
  END IF;

  SELECT coalesce(sum(quantity * unit_price), 0) INTO v_gross FROM invoice_items WHERE invoice_id = p_invoice_id;
  IF p_discount < 0 OR p_discount > v_gross THEN
    RAISE EXCEPTION 'Số tiền giảm % không hợp lệ (tổng trước giảm %)', p_discount, v_gross USING ERRCODE = 'check_violation';
  END IF;

  -- Ghi lý do trước khi phân bổ để thỏa chk_invoices_discount_reason
  IF p_discount > 0 THEN
    UPDATE invoices SET discount_reason = p_reason, discount_by = p_staff_id WHERE id = p_invoice_id;
  END IF;

  -- Làm tròn đến đồng; phần dư dồn vào dòng có giá trị lớn nhất
  WITH lines AS (
    SELECT id, quantity * unit_price AS gross,
           row_number() OVER (ORDER BY quantity * unit_price DESC, id) AS rn
    FROM invoice_items WHERE invoice_id = p_invoice_id
  ), alloc AS (
    SELECT id, rn, CASE WHEN v_gross = 0 THEN 0 ELSE round(p_discount * gross / v_gross, 0) END AS share
    FROM lines
  )
  UPDATE invoice_items ii
  SET discount_amount = CASE WHEN a.rn = 1
                             THEN p_discount - (SELECT coalesce(sum(share), 0) FROM alloc WHERE rn > 1)
                             ELSE a.share END
  FROM alloc a
  WHERE ii.id = a.id;

  IF p_discount = 0 THEN
    UPDATE invoices SET discount_reason = NULL, discount_by = NULL WHERE id = p_invoice_id;
  END IF;

  IF v_paid > 0 THEN
    INSERT INTO invoice_adjustments (invoice_id, adjustment_type, reason, old_total, new_total, detail, performed_by)
    SELECT p_invoice_id, 'ADJUST', p_reason, v_old_total, total_amount,
           jsonb_build_object('old_discount', v_old_discount, 'new_discount', p_discount), p_staff_id
    FROM invoices WHERE id = p_invoice_id;
  END IF;
END $$;

-- TT-08: hủy hóa đơn (chỉ Quản lý), không xóa
CREATE FUNCTION void_invoice(p_invoice_id bigint, p_reason text, p_staff_id bigint)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE v_inv invoices%ROWTYPE;
BEGIN
  IF coalesce(btrim(p_reason), '') = '' THEN
    RAISE EXCEPTION 'Phải ghi lý do hủy hóa đơn' USING ERRCODE = 'check_violation';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM staff s JOIN roles r ON r.id = s.role_id
                 WHERE s.id = p_staff_id AND r.code = 'MANAGER' AND s.is_active) THEN
    RAISE EXCEPTION 'Chỉ Quản lý được hủy hóa đơn' USING ERRCODE = 'insufficient_privilege';
  END IF;

  SELECT * INTO v_inv FROM invoices WHERE id = p_invoice_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Không tìm thấy hóa đơn %', p_invoice_id USING ERRCODE = 'no_data_found';
  END IF;
  IF v_inv.status = 'VOIDED' THEN
    RAISE EXCEPTION 'Hóa đơn % đã bị hủy trước đó', v_inv.invoice_code USING ERRCODE = 'check_violation';
  END IF;

  UPDATE invoices
  SET status = 'VOIDED', voided_at = now(), voided_by = p_staff_id, void_reason = p_reason
  WHERE id = p_invoice_id;

  INSERT INTO invoice_adjustments (invoice_id, adjustment_type, reason, old_total, new_total, performed_by)
  VALUES (p_invoice_id, 'VOID', p_reason, v_inv.total_amount, 0, p_staff_id);

  -- Cho phép lập lại hóa đơn cho phiếu điều trị
  UPDATE treatment_records SET status = 'PENDING_PAYMENT'
  WHERE id = v_inv.treatment_record_id AND status = 'INVOICED';
END $$;

-- Advisory lock theo (lễ tân, ngày, ca) để thu tiền và chốt két không chen nhau
CREATE FUNCTION lock_cash_shift(p_staff_id bigint, p_work_date date, p_shift varchar)
RETURNS void LANGUAGE sql AS $$
  SELECT pg_advisory_xact_lock(hashtextextended(format('cash:%s:%s:%s', p_staff_id, p_work_date, p_shift), 0));
$$;

-- TT-04: kiểm tra trước khi thu / sửa lần thu
CREATE FUNCTION trg_payments_validate() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  v_inv      invoices%ROWTYPE;
  v_previous numeric := 0;
BEGIN
  IF TG_OP IN ('UPDATE', 'DELETE') AND OLD.cash_closing_id IS NOT NULL THEN
    RAISE EXCEPTION 'Lần thu % thuộc ca đã chốt két — không được sửa/xóa', OLD.receipt_code
      USING ERRCODE = 'restrict_violation';
  END IF;
  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;

  NEW.work_date := coalesce(NEW.work_date, clinic_local(NEW.paid_at)::date);
  NEW.shift := coalesce(NEW.shift, CASE WHEN clinic_local(NEW.paid_at)::time < time '14:00'
                                        THEN 'MORNING' ELSE 'AFTERNOON' END);

  IF NEW.cash_closing_id IS NULL THEN
    PERFORM lock_cash_shift(NEW.received_by, NEW.work_date, NEW.shift);
    IF EXISTS (SELECT 1 FROM cash_closings
               WHERE receptionist_id = NEW.received_by AND work_date = NEW.work_date AND shift = NEW.shift) THEN
      RAISE EXCEPTION 'Ca % ngày % đã chốt két — không thể thêm/sửa lần thu',
        CASE NEW.shift WHEN 'MORNING' THEN 'sáng' ELSE 'chiều' END, to_char(NEW.work_date, 'DD/MM/YYYY')
        USING ERRCODE = 'restrict_violation';
    END IF;
  END IF;

  SELECT * INTO v_inv FROM invoices WHERE id = NEW.invoice_id FOR UPDATE;
  IF v_inv.status = 'VOIDED' THEN
    RAISE EXCEPTION 'Hóa đơn % đã hủy — không thể thu tiền', v_inv.invoice_code USING ERRCODE = 'check_violation';
  END IF;
  IF TG_OP = 'UPDATE' AND OLD.invoice_id = NEW.invoice_id THEN
    v_previous := OLD.amount;
  END IF;
  IF NEW.amount > v_inv.balance_due + v_previous THEN
    RAISE EXCEPTION 'Số tiền thu % vượt quá số còn nợ % của hóa đơn %',
      NEW.amount, v_inv.balance_due + v_previous, v_inv.invoice_code USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;

CREATE FUNCTION trg_payments_refresh() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP IN ('UPDATE', 'DELETE') THEN
    PERFORM refresh_invoice_totals(OLD.invoice_id);
  END IF;
  IF TG_OP = 'INSERT' OR (TG_OP = 'UPDATE' AND NEW.invoice_id <> OLD.invoice_id) THEN
    PERFORM refresh_invoice_totals(NEW.invoice_id);
  END IF;
  RETURN NULL;
END $$;

-- TT-07: chốt két — tổng tiền mặt trong ca, khóa mọi lần thu của ca
CREATE FUNCTION close_cash_drawer(p_receptionist_id bigint, p_work_date date, p_shift varchar,
                                  p_counted_cash numeric, p_note text DEFAULT NULL)
RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE
  v_expected numeric;
  v_id       bigint;
BEGIN
  IF p_work_date > clinic_local(now())::date
     OR (p_work_date = clinic_local(now())::date AND p_shift = 'AFTERNOON'
         AND clinic_local(now())::time < time '14:00') THEN
    RAISE EXCEPTION 'Không thể chốt két cho ca chưa bắt đầu' USING ERRCODE = 'check_violation';
  END IF;
  PERFORM lock_cash_shift(p_receptionist_id, p_work_date, p_shift);

  SELECT coalesce(sum(amount) FILTER (WHERE method = 'CASH'), 0) INTO v_expected
  FROM payments
  WHERE received_by = p_receptionist_id AND work_date = p_work_date AND shift = p_shift
    AND cash_closing_id IS NULL;

  INSERT INTO cash_closings (receptionist_id, work_date, shift, expected_cash, counted_cash, note)
  VALUES (p_receptionist_id, p_work_date, p_shift, v_expected, p_counted_cash, p_note)
  RETURNING id INTO v_id;

  UPDATE payments SET cash_closing_id = v_id
  WHERE received_by = p_receptionist_id AND work_date = p_work_date AND shift = p_shift
    AND cash_closing_id IS NULL;
  RETURN v_id;
END $$;

-- DT-09: ghi lịch sử trước/sau
CREATE FUNCTION trg_audit() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  v_old jsonb;
  v_new jsonb;
BEGIN
  IF TG_OP IN ('UPDATE', 'DELETE') THEN
    v_old := to_jsonb(OLD);
  END IF;
  IF TG_OP IN ('INSERT', 'UPDATE') THEN
    v_new := to_jsonb(NEW);
  END IF;
  IF TG_OP = 'UPDATE' AND (v_old - 'updated_at') = (v_new - 'updated_at') THEN
    RETURN NULL;
  END IF;

  INSERT INTO audit_logs (table_name, record_id, action, old_data, new_data, reason, changed_by)
  VALUES (TG_TABLE_NAME, (coalesce(v_new, v_old) ->> 'id')::bigint, TG_OP, v_old, v_new,
          nullif(current_setting('app.change_reason', true), ''), current_staff_id());
  RETURN NULL;
END $$;

