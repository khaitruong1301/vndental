-- =============================================================================
-- ClinicCybersoftDB — Hệ thống quản lý Nha khoa Nụ Cười Việt
-- Nguồn: .claude/docs/requirements/use-case.md
--
-- Quy ước:
--   * Bảng/cột snake_case, khóa chính bigint identity, tiền VND numeric(14,2).
--   * Thời gian lưu timestamptz; quy đổi giờ phòng khám bằng clinic_local().
--   * Ứng dụng gọi `SET LOCAL app.staff_id = '<id nhân viên>'` (và tùy chọn
--     `app.change_reason`) đầu mỗi transaction để trigger ghi người thao tác.
--   * Không xóa cứng hồ sơ, lịch hẹn, phiếu điều trị, hóa đơn (lưu trữ 5 năm).
