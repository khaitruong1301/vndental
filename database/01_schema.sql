  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doctor_id  bigint      NOT NULL REFERENCES staff(id),
  work_date  date        NOT NULL,
  shift      varchar(10) NOT NULL CHECK (shift IN ('MORNING', 'AFTERNOON')),
