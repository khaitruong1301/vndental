\set ON_ERROR_STOP on
BEGIN;

CREATE EXTENSION IF NOT EXISTS btree_gist;  -- ràng buộc chống trùng lịch (LH-07)
CREATE EXTENSION IF NOT EXISTS pg_trgm;     -- tìm bệnh nhân theo tên (BN-01)

-- -----------------------------------------------------------------------------
-- Hàm tiện ích dùng trong ràng buộc
-- -----------------------------------------------------------------------------
CREATE FUNCTION clinic_local(ts timestamptz) RETURNS timestamp
LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
  SELECT ts AT TIME ZONE 'Asia/Ho_Chi_Minh'
$$;

-- Số lượng kiểu Việt Nam cho thông báo: bỏ số 0 thừa, dấu phẩy thập phân (3.00 → 3, 1.50 → 1,5)
CREATE FUNCTION fmt_qty(n numeric) RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
  SELECT replace(trim_scale(n)::text, '.', ',')
$$;

CREATE FUNCTION current_staff_id() RETURNS bigint
LANGUAGE sql STABLE AS $$
  SELECT nullif(current_setting('app.staff_id', true), '')::bigint
$$;

CREATE FUNCTION trg_set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END $$;

CREATE FUNCTION trg_prevent_delete() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'Không được xóa bản ghi bảng % — dùng trạng thái hủy/lưu trữ', TG_TABLE_NAME
    USING ERRCODE = 'restrict_violation';
END $$;

CREATE FUNCTION trg_immutable() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'Bảng % chỉ cho phép thêm mới, không sửa/xóa', TG_TABLE_NAME
    USING ERRCODE = 'restrict_violation';
END $$;

CREATE SEQUENCE patient_code_seq;
CREATE SEQUENCE treatment_plan_code_seq;
CREATE SEQUENCE treatment_record_code_seq;
CREATE SEQUENCE invoice_code_seq;
CREATE SEQUENCE receipt_code_seq;

-- =============================================================================
-- 1. TÀI KHOẢN & PHÂN QUYỀN (UC-00, QT-05)
-- =============================================================================
CREATE TABLE roles (
  id             smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code           varchar(30)  NOT NULL UNIQUE,
  name           varchar(100) NOT NULL,
  parent_role_id smallint REFERENCES roles(id),
  description    text
);
COMMENT ON TABLE roles IS 'Vai trò: Lễ tân, Bác sĩ, Quản lý. parent_role_id thể hiện kế thừa (Quản lý kế thừa Lễ tân).';

CREATE TABLE permissions (
  id     smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code   varchar(20)  NOT NULL UNIQUE,
  module varchar(30)  NOT NULL,
  name   varchar(200) NOT NULL
);
COMMENT ON TABLE permissions IS 'Quyền theo mã use case (UC-00, BN-01, LH-02, ...).';

CREATE TABLE role_permissions (
  role_id       smallint NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
  permission_id smallint NOT NULL REFERENCES permissions(id) ON DELETE CASCADE,
  PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE staff (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_id              smallint     NOT NULL REFERENCES roles(id),
  staff_code           varchar(20)  NOT NULL UNIQUE,
  full_name            varchar(150) NOT NULL,
  phone                varchar(20),
  email                varchar(150),
  username             varchar(50)  NOT NULL,
  password_hash        varchar(255) NOT NULL,
  must_change_password boolean      NOT NULL DEFAULT true,
  is_part_time         boolean      NOT NULL DEFAULT false,
  is_active            boolean      NOT NULL DEFAULT true,
  last_login_at        timestamptz,
  token_version        integer      NOT NULL DEFAULT 0,
  created_at           timestamptz  NOT NULL DEFAULT now(),
  updated_at           timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_staff_username ON staff (lower(username));
COMMENT ON TABLE staff IS 'Nhân viên + tài khoản đăng nhập (UC-00, QT-05).';
COMMENT ON COLUMN staff.token_version IS 'Tăng khi đổi mật khẩu / khóa tài khoản → mọi phiên đăng nhập cũ (JWT) hết hiệu lực.';

CREATE FUNCTION trg_staff_token_version() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.password_hash IS DISTINCT FROM OLD.password_hash OR NEW.is_active IS DISTINCT FROM OLD.is_active THEN
    NEW.token_version := OLD.token_version + 1;
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER bump_token_version BEFORE UPDATE ON staff
  FOR EACH ROW EXECUTE FUNCTION trg_staff_token_version();

