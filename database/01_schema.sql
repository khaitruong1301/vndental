-- TT-02: giá dịch vụ / thuốc đang hiệu lực tại một ngày
CREATE FUNCTION get_service_price(p_service_id bigint, p_on date DEFAULT clinic_local(now())::date)
RETURNS numeric LANGUAGE plpgsql STABLE AS $$
DECLARE v_price numeric;
BEGIN
  SELECT price INTO v_price FROM service_prices
  WHERE service_id = p_service_id AND effective_from <= p_on
  ORDER BY effective_from DESC LIMIT 1;
  IF v_price IS NULL THEN
    RAISE EXCEPTION 'Dịch vụ % chưa có giá hiệu lực tại ngày %', p_service_id, p_on USING ERRCODE = 'no_data_found';
  END IF;
  RETURN v_price;
END $$;

CREATE FUNCTION get_item_price(p_item_id bigint, p_on date DEFAULT clinic_local(now())::date)
RETURNS numeric LANGUAGE plpgsql STABLE AS $$
DECLARE v_price numeric;
BEGIN
  SELECT price INTO v_price FROM item_prices
  WHERE item_id = p_item_id AND effective_from <= p_on
  ORDER BY effective_from DESC LIMIT 1;
  IF v_price IS NULL THEN
    RAISE EXCEPTION 'Thuốc/vật tư % chưa có giá hiệu lực tại ngày %', p_item_id, p_on USING ERRCODE = 'no_data_found';
  END IF;
  RETURN v_price;
END $$;

-- QT-02: giá đã có hiệu lực thì không sửa/xóa
CREATE FUNCTION trg_prices_protect() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.effective_from <= clinic_local(now())::date THEN
    RAISE EXCEPTION 'Giá đã hiệu lực từ % — không được sửa/xóa, hãy tạo giá mới với ngày hiệu lực mới', OLD.effective_from
